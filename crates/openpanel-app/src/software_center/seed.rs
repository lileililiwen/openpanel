/// Build the embedded manifest. Used by the embedded source and by the
/// service on first boot when no remote manifest has ever been activated.
pub fn embedded_manifest() -> Result<CatalogManifest, super::SoftwareCenterError> {
    let manifest = CatalogManifest {
        schema: 1,
        issued_at: "2024-05-10T00:00:00Z".to_owned(),
        source_url: "https://catalog.openpanel.invalid/v1/manifest.json".to_owned(),
        entries: entries(),
    };
    manifest
        .validate()
        .map_err(|_| super::SoftwareCenterError::Invalid("seed entry invalid".into()))?;
    Ok(manifest)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn seed_manifest_validates() {
        let manifest = embedded_manifest().expect("seed manifest must validate");
        assert!(manifest.entries.len() >= 25);
    }

    #[test]
    fn php_runtimes_are_mutually_unique() {
        let ids: Vec<_> = entries().into_iter().map(|entry| entry.id).collect();
        let unique: std::collections::BTreeSet<_> = ids.iter().collect();
        assert_eq!(unique.len(), ids.len());
    }
}
