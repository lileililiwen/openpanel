//! Embedded recovery seed for the Software Center aggregator.
//!
//! This manifest is the *last-resort* fallback used only on first boot
//! when no remote manifest has ever been activated and the network is
//! unreachable. The remote signed manifest is the source of truth; this
//! seed exists to keep the page useful when offline.
//!
//! The set is deliberately a starting point covering the most common
//! hosting stack: web servers, PHP runtimes, databases, caches, operator
//! tools, and one-click applications. Every entry has at least one tag,
//! a license, a developer, a homepage, a short and long description, and
//! at least one version. Web entries have a pinned `ArtifactPin` with a
//! published digest (or a documented placeholder when the upstream does
//! not publish SHA-256 — those entries will fail the live digest check
//! and are clearly marked).
//!
//! The seed is build-time developer data; `.expect` on developer-authored
//! values is intentional so that any future schema drift fails loudly at
//! compile or test time rather than silently shipping a half-built
//! manifest.
#![allow(clippy::expect_used, clippy::too_many_arguments, missing_docs)]

use openpanel_domain::software_center::{
    ArtifactPin, CatalogEntryRecipe, CatalogManifest, Category, EntryKind, Homepage, License,
    SupportedPlatform, Tag, VersionSpec,
};

/// Maximum disk delta estimate for a typical install. Used as a fallback
/// when the recipe does not declare one.
const fn mib(mebibytes: u64) -> u64 {
    mebibytes * 1024 * 1024
}

fn artifact(url: &str, sha256: &str, archive_root: &str, sha1: Option<&str>) -> ArtifactPin {
    ArtifactPin {
        url: Homepage::new(url).expect("seed artifact url must validate"),
        sha256: sha256.to_owned(),
        archive_root: archive_root.to_owned(),
        archive_type: "tar.gz".to_owned(),
        sha1: sha1.map(str::to_owned),
    }
}

fn file_artifact(url: &str, sha256: &str, filename: &str) -> ArtifactPin {
    ArtifactPin {
        url: Homepage::new(url).expect("seed artifact url must validate"),
        sha256: sha256.to_owned(),
        archive_root: filename.to_owned(),
        archive_type: "file".to_owned(),
        sha1: None,
    }
}

fn version(
    version: &str,
    size_bytes: u64,
    artifact: Option<ArtifactPin>,
    packages: Vec<&str>,
    supports_php: Vec<&str>,
    released_at: Option<&str>,
) -> VersionSpec {
    VersionSpec {
        version: version.to_owned(),
        size_bytes,
        changelog_url: None,
        artifact,
        packages: packages.into_iter().map(str::to_owned).collect(),
        supports_php: supports_php.into_iter().map(str::to_owned).collect(),
        released_at: released_at.map(str::to_owned),
    }
}

/// Build the default platform list for a seed entry. Most entries
/// support every host OpenPanel recognizes. Specific entries can
/// override by passing a non-empty `platforms` list.
fn default_platforms() -> Vec<SupportedPlatform> {
    [
        "ubuntu 22.04 x86_64",
        "ubuntu 22.04 aarch64",
        "ubuntu 24.04 x86_64",
        "ubuntu 24.04 aarch64",
        "debian 12 x86_64",
        "debian 12 aarch64",
    ]
    .iter()
    .filter_map(|value| {
        let mut parts = value.split_whitespace();
        let distribution = parts.next()?;
        let release = parts.next()?;
        let architecture = parts.next()?;
        SupportedPlatform::new(distribution, release, architecture).ok()
    })
    .collect()
}

fn entry(
    id: &str,
    name: &str,
    description: &str,
    long: &str,
    category: Category,
    kind: EntryKind,
    tags: &[&str],
    license: &str,
    developer: &str,
    homepage: &str,
    versions: Vec<VersionSpec>,
    dependencies: Vec<&str>,
    conflicts: Vec<&str>,
    icon: Option<&str>,
) -> CatalogEntryRecipe {
    entry_with_platforms(
        id,
        name,
        description,
        long,
        category,
        kind,
        tags,
        license,
        developer,
        homepage,
        versions,
        dependencies,
        conflicts,
        icon,
        default_platforms(),
    )
}

fn entry_with_platforms(
    id: &str,
    name: &str,
    description: &str,
    long: &str,
    category: Category,
    kind: EntryKind,
    tags: &[&str],
    license: &str,
    developer: &str,
    homepage: &str,
    versions: Vec<VersionSpec>,
    dependencies: Vec<&str>,
    conflicts: Vec<&str>,
    icon: Option<&str>,
    platforms: Vec<SupportedPlatform>,
) -> CatalogEntryRecipe {
    CatalogEntryRecipe {
        id: id.to_owned(),
        name: name.to_owned(),
        description: description.to_owned(),
        long_description: long.to_owned(),
        category,
        kind,
        tags: tags
            .iter()
            .map(|value| Tag::new(value).expect("seed tag must validate"))
            .collect(),
        license: License::new(license).expect("seed license must validate"),
        developer: developer.to_owned(),
        homepage: Homepage::new(homepage).expect("seed homepage must validate"),
        versions,
        platforms,
        dependencies: dependencies.into_iter().map(str::to_owned).collect(),
        conflicts: conflicts.into_iter().map(str::to_owned).collect(),
        icon: icon.map(str::to_owned),
        screenshot: None,
    }
}

